import { useMemo, useState } from 'react'
import { Link, useNavigate, useParams } from 'react-router-dom'
import { ArrowLeft, FileWarning, RefreshCw, ShieldCheck } from 'lucide-react'

import {
  Alert,
  Button,
  Card,
  CardBody,
  CardHeader,
  EmptyState,
  ErrorState,
  InfoList,
  InfoRow,
  PageHeader,
  Skeleton,
} from '@/components/common'
import { FileTypeIcon } from '@/components/files/FileTypeIcon'
import { WatermarkVerificationBadge } from '@/components/security/SecurityBadges'
import { WatermarkedRendition } from '@/components/watermark/WatermarkPreview'
import { HashCopy } from '@/pages/watermarks/watermarkParts'
import { useToast } from '@/context/ToastContext'
import { useAsync, useDocumentTitle } from '@/hooks'
import { adminPath } from '@/routes/navigation'
import { toApiError } from '@/services'
import { buildRenditionPreview } from '@/services/mock/previews'
import { watermarkService } from '@/services/watermark.service'
import { formatBytes, formatDateTime, formatRelativeTime } from '@/utils/format'
import { WATERMARK_PATTERN_LABEL } from '@/utils/labels'
import type { ApiError } from '@/types'

function isNotFound(error: ApiError | null): boolean {
  if (!error) return false
  return error.status === 404 || error.code === 'not_found' || /not found/i.test(error.message)
}

/** Single watermark record: the backend rendition plus its audit metadata. */
export default function WatermarkDetailPage() {
  const { watermarkId = '' } = useParams<{ watermarkId: string }>()
  const navigate = useNavigate()
  const toast = useToast()
  const [verifying, setVerifying] = useState(false)

  const recordState = useAsync(() => watermarkService.get(watermarkId), [watermarkId])
  const record = recordState.data
  useDocumentTitle(record ? `Watermark · ${record.fileName}` : 'Watermark record')

  /* Recipient-specific records are linked together so an operator can pivot
     from one rendition to the others issued to the same recipient. */
  const recipientUsername = record?.recipientUsername
  const relatedState = useAsync(
    () => watermarkService.list({ recipientUsername, pageSize: 8 }),
    [recipientUsername],
  )

  /* The lines the backend would have burned into the rendition. */
  const watermarkLines = useMemo(() => {
    if (!record) return []
    return [
      record.recipientUsername,
      `Access ID ${record.accessId}`,
      formatDateTime(record.generatedAt),
      'SecureFile',
    ]
  }, [record])

  const renditionUrl = useMemo(() => {
    if (!record) return ''
    if (record.previewUrl) return record.previewUrl
    /*
     * MOCK-ONLY fallback. In production the API returns `previewUrl` pointing at
     * the real, already-watermarked rendition. `buildRenditionPreview` only
     * fabricates an SVG for local development so the layout matches production;
     * the real watermark is embedded into the generated bytes by the backend.
     */
    return buildRenditionPreview({
      title: record.fileName,
      subtitle: record.recipientUsername,
      watermarkLines,
      opacity: record.opacity,
      size: record.size,
    })
  }, [record, watermarkLines])

  const handleVerify = async () => {
    if (!record) return
    setVerifying(true)
    try {
      const updated = await watermarkService.verify(record.id)
      recordState.setData(updated)
      toast.success(
        'Integrity verified',
        `The ${updated.fileName} rendition hash matches the recorded output (${updated.hashAlgorithm}).`,
      )
    } catch (failure) {
      toast.error('Verification failed', toApiError(failure).message)
    } finally {
      setVerifying(false)
    }
  }

  if (recordState.loading) {
    return (
      <div className="space-y-5">
        <Skeleton className="h-8 w-64" />
        <div className="grid gap-5 lg:grid-cols-[minmax(0,1fr)_360px]">
          <Skeleton className="h-[420px] rounded-xl" />
          <Skeleton className="h-[420px] rounded-xl" />
        </div>
      </div>
    )
  }

  if (recordState.error) {
    if (isNotFound(recordState.error)) {
      return (
        <Card>
          <EmptyState
            icon={<FileWarning size={20} />}
            title="Watermark record not found"
            description="This rendition record may have been removed, or you no longer have access to it."
            action={
              <Button variant="outline" onClick={() => navigate(adminPath('/watermarks'))}>
                Back to watermark records
              </Button>
            }
          />
        </Card>
      )
    }
    return (
      <ErrorState
        error={recordState.error}
        title="Could not load this watermark record"
        onRetry={() => void recordState.reload()}
      />
    )
  }

  if (!record) return null

  const related = (relatedState.data?.results ?? []).filter((item) => item.id !== record.id)

  return (
    <div className="animate-fade-in space-y-5">
      <PageHeader
        breadcrumbs={[{ label: 'Watermark records', to: adminPath('/watermarks') }, { label: record.fileName }]}
        title={record.fileName}
        badge={<WatermarkVerificationBadge status={record.verificationStatus} />}
        description={`Recipient-scoped rendition for ${record.recipientUsername} · generated ${formatRelativeTime(record.generatedAt)}`}
        actions={
          <>
            <Button
              variant="outline"
              leftIcon={<ArrowLeft size={16} />}
              onClick={() => navigate(adminPath('/watermarks'))}
            >
              Back
            </Button>
            <Button
              leftIcon={<RefreshCw size={16} />}
              loading={verifying}
              onClick={() => void handleVerify()}
            >
              Verify integrity
            </Button>
          </>
        }
      />

      <div className="grid gap-5 lg:grid-cols-[minmax(0,1fr)_380px]">
        <div className="space-y-5">
          <Card>
            <CardHeader
              title="Watermarked rendition"
              description="The protected asset the recipient receives — the watermark is part of the generated bytes."
            />
            <CardBody>
              <WatermarkedRendition
                src={renditionUrl}
                alt={`Watermarked rendition of ${record.fileName}`}
                watermarkLines={watermarkLines}
                caption="Preview of the backend-generated rendition. The recipient watermark is embedded directly into the image pixels and is not a CSS overlay that can be removed in the browser."
              />
            </CardBody>
          </Card>

          {related.length > 0 ? (
            <Card>
              <CardHeader
                title="Other renditions for this recipient"
                description={`Records issued to ${record.recipientUsername}.`}
              />
              <CardBody className="space-y-2">
                {related.map((item) => (
                  <Link
                    key={item.id}
                    to={adminPath(`/watermarks/${item.id}`)}
                    className="flex items-center justify-between gap-3 rounded-lg border border-line px-3 py-2.5 transition-colors hover:border-brand-300 hover:bg-brand-50/40"
                  >
                    <span className="flex min-w-0 items-center gap-2.5">
                      <FileTypeIcon extension={item.extension} size="sm" />
                      <span className="min-w-0">
                        <span className="block truncate text-[13px] font-medium text-ink">
                          {item.fileName}
                        </span>
                        <span className="block truncate font-mono text-[11.5px] text-ink-muted">
                          {item.accessId}
                        </span>
                      </span>
                    </span>
                    <WatermarkVerificationBadge status={item.verificationStatus} />
                  </Link>
                ))}
              </CardBody>
            </Card>
          ) : null}
        </div>

        <div className="space-y-5">
          <Card>
            <CardHeader
              title="Record details"
              icon={<ShieldCheck size={16} />}
              flush
            />
            <CardBody>
              <InfoList>
                <InfoRow
                  label="Original file"
                  value={
                    <span className="flex items-center justify-end gap-2">
                      <FileTypeIcon extension={record.extension} size="sm" />
                      <span className="truncate font-medium">{record.fileName}</span>
                    </span>
                  }
                />
                <InfoRow label="Recipient username" value={record.recipientUsername} mono />
                <InfoRow label="Access ID" value={record.accessId} mono />
                <InfoRow
                  label="Generated"
                  value={
                    <span className="flex flex-col items-end">
                      <span>{formatDateTime(record.generatedAt)}</span>
                      <span className="text-[11.5px] text-ink-muted">
                        {formatRelativeTime(record.generatedAt)}
                      </span>
                    </span>
                  }
                />
              </InfoList>

              <div className="mt-3 border-t border-line pt-3">
                <p className="mb-1.5 text-[12.5px] font-medium text-ink-soft">
                  Output file hash
                </p>
                <HashCopy hash={record.outputHash} edge={10} />
                <p className="mt-1.5 text-[11.5px] text-ink-muted">
                  Algorithm · {record.hashAlgorithm}
                </p>
              </div>

              <div className="mt-3 border-t border-line pt-1">
                <InfoList>
                  <InfoRow
                    label="Verification status"
                    value={<WatermarkVerificationBadge status={record.verificationStatus} />}
                  />
                  <InfoRow
                    label="Pattern"
                    value={WATERMARK_PATTERN_LABEL[record.pattern]}
                  />
                  <InfoRow label="Opacity" value={`${Math.round(record.opacity * 100)}%`} />
                  <InfoRow label="Size" value={`${record.size.toFixed(2)}×`} />
                  <InfoRow label="Rendition size" value={formatBytes(record.sizeBytes)} mono />
                </InfoList>
              </div>
            </CardBody>
          </Card>

          <Alert tone="info" title="Permanent and recipient-specific">
            Each recipient gets their own rendition with their identity, access ID and generation
            timestamp embedded by the backend. The configuration above describes what was written
            into the bytes — not a browser overlay.
          </Alert>
        </div>
      </div>
    </div>
  )
}
